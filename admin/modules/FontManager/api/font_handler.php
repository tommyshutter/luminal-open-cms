require_once dirname(__DIR__, 3) . '/auth.php';
requireAuth();

header('Content-Type: application/json');

$fontsDir = SITE_ROOT . '/media/fonts/';
$cssFile = SITE_ROOT . '/css/custom-fonts.css';

if (!is_dir($fontsDir)) {
    mkdir($fontsDir, 0755, true);
}

$action = $_REQUEST['action'] ?? null;

// --- Main Action Router ---
switch ($action) {
    case 'upload': handle_upload(); break;
    case 'list': handle_list(); break;
    case 'delete': handle_delete(); break;
    default: echo json_encode(['success' => false, 'message' => 'Invalid action.']);
}

function handle_upload() {
    global $fontsDir;
    if (empty($_FILES['fonts'])) {
        echo json_encode(['success' => false, 'message' => 'No files were uploaded.']);
        return;
    }

    $uploaded = 0;
    foreach ($_FILES['fonts']['tmp_name'] as $index => $tmp_name) {
        if ($_FILES['fonts']['error'][$index] === UPLOAD_ERR_OK) {
            $filename = basename($_FILES['fonts']['name'][$index]); // Using basename for security
            $destination = $fontsDir . $filename;
            if (move_uploaded_file($tmp_name, $destination)) {
                $uploaded++;
            }
        }
    }

    if ($uploaded > 0) {
        update_css_file();
        echo json_encode(['success' => true, 'message' => "$uploaded font file(s) uploaded successfully."]);
    } else {
        echo json_encode(['success' => false, 'message' => 'File upload failed. Check server permissions.']);
    }
}

function handle_list() {
    echo json_encode(['success' => true, 'fonts' => parse_css_for_fonts()]);
}

function handle_delete() {
    global $fontsDir;
    $fontFamilyToDelete = $_POST['fontFamily'] ?? '';
    if (empty($fontFamilyToDelete)) {
        echo json_encode(['success' => false, 'message' => 'No font family specified for deletion.']);
        return;
    }

    $files = array_diff(scandir($fontsDir), ['.', '..']);
    $deletedCount = 0;
    foreach ($files as $file) {
        $font_name_from_file = preg_replace('/\.(ttf|woff|woff2)$/i', '', $file);
        $font_name_from_file = str_replace(['_', '-'], ' ', $font_name_from_file);
        $font_name_from_file = ucwords(strtolower($font_name_from_file));
        if ($font_name_from_file === $fontFamilyToDelete) {
            if (unlink($fontsDir . $file)) {
                $deletedCount++;
            }
        }
    }

    update_css_file();
    echo json_encode(['success' => true, 'message' => "Deleted {$deletedCount} file(s) for font '{$fontFamilyToDelete}'."]);
}

function parse_css_for_fonts() {
    global $cssFile;
    $fonts = [];
    if (file_exists($cssFile)) {
        $content = file_get_contents($cssFile);
        preg_match_all("/font-family: '([^']+)';/", $content, $matches);
        if (!empty($matches[1])) {
            foreach (array_unique($matches[1]) as $fontFamily) {
                $fonts[] = ['fontFamily' => $fontFamily];
            }
        }
    }
    return $fonts;
}


