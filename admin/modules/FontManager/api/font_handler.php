function update_css_file() {
    global $fontsDir, $cssFile;
    $files = array_diff(scandir($fontsDir), ['.', '..']);
    $css_content = "/**\n * @file SITE-ROOT/css/custom-fonts.css\n * @version " . date('Y.m.d.His') . "\n * @description Auto-generated by the Font Manager.\n */\n\n";

    // --- FIX START: Determine the correct root-relative path ---
    // This calculates the path from the web root to the site's base directory.
    // It gracefully handles being in the root ('/') or a subdirectory ('/mysite/').
    $site_path = str_replace($_SERVER['DOCUMENT_ROOT'], '', str_replace('\\', '/', SITE_ROOT));
    if (substr($site_path, -1) !== '/') {
        $site_path .= '/';
    }
    $font_url_path = $site_path . 'fonts/';
    // --- FIX END ---

    $font_families = [];
    foreach ($files as $file) {
        $path = $fontsDir . $file;
        $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
        if (in_array($ext, ['ttf', 'woff', 'woff2'])) {
            $font_name = preg_replace('/\.(ttf|woff|woff2)$/i', '', $file);
            $font_name = str_replace(['_', '-'], ' ', $font_name);
            $font_name = ucwords(strtolower($font_name));
            $font_families[$font_name][$ext] = $file;
        }
    }

    foreach ($font_families as $name => $formats) {
        $css_content .= "@font-face {\n";
        $css_content .= "    font-family: '{$name}';\n";
        $sources = [];
        // --- FIX START: Use the new root-relative path variable ---
        if (isset($formats['woff2'])) $sources[] = "url('{$font_url_path}{$formats['woff2']}') format('woff2')";
        if (isset($formats['woff']))  $sources[] = "url('{$font_url_path}{$formats['woff']}') format('woff')";
        if (isset($formats['ttf']))   $sources[] = "url('{$font_url_path}{$formats['ttf']}') format('truetype')";
        // --- FIX END ---
        $css_content .= "    src: " . implode(",\n         ", $sources) . ";\n";
        $css_content .= "    font-weight: normal;\n";
        $css_content .= "    font-style: normal;\n";
        $css_content .= "}\n\n";
    }

    file_put_contents($cssFile, $css_content, LOCK_EX);
}
